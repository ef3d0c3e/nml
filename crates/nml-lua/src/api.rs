use std::fmt::Write;
use std::fs;
use std::io;
use std::path::Path;

use mlua::Lua;
use mlua::Table;

/// A function of the `nml` table, declared with `#[api]`.
///
/// ```
/// /// Adds two numbers.
/// #[nml_lua::api]
/// fn add(_lua: &mlua::Lua, a: f64, b: f64) -> mlua::Result<f64> {
///     Ok(a + b)
/// }
/// assert_eq!(ADD.name, "add");
/// assert_eq!(ADD.params, &[("a", "number"), ("b", "number")]);
/// assert_eq!(ADD.returns, Some("number"));
/// ```
///
/// A Lua keyword cannot be a name:
/// ```compile_fail
/// #[nml_lua::api]
/// fn nil(_lua: &mlua::Lua) -> mlua::Result<()> { Ok(()) }
/// ```
/// The Lua state comes first:
/// ```compile_fail
/// #[nml_lua::api]
/// fn f() -> mlua::Result<()> { Ok(()) }
/// ```
/// A type without a LuaCATS translation needs one:
/// ```compile_fail
/// #[nml_lua::api]
/// fn f(_lua: &mlua::Lua, x: std::path::PathBuf) -> mlua::Result<()> { Ok(()) }
/// ```
#[derive(Debug, Clone, Copy)]
pub struct ApiFunction {
	pub name: &'static str,
	/// Markdown, one line per doc comment line.
	pub doc: &'static str,
	/// Names and LuaCATS types. A type ending with `?` is optional.
	pub params: &'static [(&'static str, &'static str)],
	pub returns: Option<&'static str>,
	pub register: fn(&Lua, &Table) -> mlua::Result<()>,
}

/// A Lua class declared with `#[userdata]`.
#[derive(Debug, Clone, Copy)]
pub struct LuaClass {
	/// The class name in the declarations, `nml.Element`.
	pub name: &'static str,
	pub doc: &'static str,
	pub fields: &'static [LuaField],
}

#[derive(Debug, Clone, Copy)]
pub struct LuaField {
	pub name: &'static str,
	/// The LuaCATS type.
	pub ty: &'static str,
	pub doc: &'static str,
	/// Scripts can read it but not assign it.
	pub readonly: bool,
}

/// Every class scripts see.
pub const CLASSES: &[LuaClass] = &[
	crate::events::ElementData::LUA_CLASS,
	crate::rules::LuaAtom::LUA_CLASS,
	crate::elements::NODE_CLASS,
];

/// Every function of the `nml` table.
pub const API: &[ApiFunction] = &[
	crate::events::ON,
	crate::post_parse::POST_PARSE,
	crate::files::READ,
	crate::variables::VARIABLE,
	crate::deferred::DEFER,
	crate::elements::ELEMENT,
	crate::deferred::PAGES,
	crate::rules::RULE,
	crate::rules::CAPTURE,
	crate::rules::OPTIONAL,
	crate::rules::MANY,
	crate::rules::ONE_OF,
	crate::rules::RUN,
	crate::rules::SAME,
];

/// Adds API functions to the `nml` table.
pub(crate) fn register(lua: &Lua, table: &Table, functions: &[ApiFunction]) -> mlua::Result<()> {
	for function in functions {
		(function.register)(lua, table)?;
	}
	Ok(())
}

/// The LuaCATS declarations of API functions and classes, for LuaLS.
pub fn luacats(functions: &[ApiFunction], classes: &[LuaClass], values: &[(&str, &str)]) -> String {
	let mut out = String::from(
		"---@meta\n-- Generated by NML from its Lua bindings: do not edit.\n\n\
		---The NML API.\nnml = {}\n",
	);
	for class in classes {
		out.push('\n');
		for line in class.doc.lines() {
			writeln!(out, "---{line}").unwrap();
		}
		writeln!(out, "---@class {}", class.name).unwrap();
		for field in class.fields {
			let mut doc = field.doc.replace('\n', " ");
			if field.readonly {
				doc = format!("(read-only) {doc}");
			}
			writeln!(
				out,
				"---@field {} {} {}",
				field.name,
				field.ty,
				doc.trim_end()
			)
			.unwrap();
		}
	}
	for function in functions {
		out.push('\n');
		for line in function.doc.lines() {
			writeln!(out, "---{line}").unwrap();
		}
		for (name, ty) in function.params {
			match ty.strip_suffix('?') {
				Some(ty) => writeln!(out, "---@param {name}? {ty}").unwrap(),
				None => writeln!(out, "---@param {name} {ty}").unwrap(),
			}
		}
		if let Some(returns) = function.returns {
			writeln!(out, "---@return {returns}").unwrap();
		}
		let params: Vec<_> = function.params.iter().map(|(name, _)| *name).collect();
		writeln!(
			out,
			"function nml.{}({}) end",
			function.name,
			params.join(", ")
		)
		.unwrap();
	}
	for (name, doc) in values {
		writeln!(out, "\n---{doc}\n---@type nml.Atom\nnml.{name} = nil").unwrap();
	}
	out
}

/// Where the declarations go, relative to the workspace root.
pub const TYPES_DIR: &str = ".nml/types";

/// The LuaLS configuration: Lua 5.4, the declarations, and the sandbox.
const LUARC: &str = r#"{
	"runtime.version": "Lua 5.4",
	"runtime.builtin": {
		"io": "disable",
		"os": "disable",
		"debug": "disable",
		"package": "disable"
	},
	"workspace.library": [".nml/types"],
	"diagnostics.globals": ["nml"]
}
"#;

/// Writes the declarations of the API for LuaLS, and a `.luarc.json` unless the workspace
/// has one.
pub fn write_types(root: &Path) -> io::Result<()> {
	let dir = root.join(TYPES_DIR);
	fs::create_dir_all(&dir)?;
	fs::write(
		dir.join("nml.lua"),
		luacats(API, CLASSES, crate::rules::VALUES),
	)?;
	let luarc = root.join(".luarc.json");
	if !luarc.exists() {
		fs::write(luarc, LUARC)?;
	}
	Ok(())
}

#[cfg(test)]
mod tests {
	use nml_lua_macros::api;

	use super::*;
	use crate::Limits;
	use crate::Runtime;

	/// Repeats a string.
	///
	/// With `separator` between the copies.
	#[api]
	fn replicate(
		_lua: &Lua,
		text: String,
		count: i64,
		separator: Option<String>,
	) -> mlua::Result<String> {
		let copies = vec![text; count.max(0) as usize];
		Ok(copies.join(separator.as_deref().unwrap_or("")))
	}

	/// Calls `callback` with nothing.
	#[api(returns = "any")]
	fn call(
		_lua: &Lua,
		#[lua(type = "fun(): any")] callback: mlua::Function,
	) -> mlua::Result<mlua::Value> {
		callback.call(())
	}

	/// Does nothing.
	#[api]
	fn nothing(_lua: &Lua) -> mlua::Result<()> {
		Ok(())
	}

	#[test]
	fn bindings() {
		let runtime = Runtime::new(Limits::default()).unwrap();
		register(runtime.lua(), &runtime.api(), &[REPLICATE, CALL, NOTHING]).unwrap();
		let value: String = runtime
			.lua()
			.load(
				"return nml.replicate('ab', 3, '-') .. nml.replicate('x', 2) .. nml.call(function() return '!' end)",
			)
			.eval()
			.unwrap();
		assert_eq!(value, "ab-ab-abxx!");
		runtime.run("nml.nothing()", "test").unwrap();
		let error = runtime.run("nml.replicate(1)", "test").unwrap_err();
		assert!(error.to_string().contains("bad argument #2"), "{error}");
	}

	#[test]
	fn declarations() {
		assert_eq!(
			luacats(&[REPLICATE, CALL, NOTHING], &[], &[]),
			"---@meta
-- Generated by NML from its Lua bindings: do not edit.

---The NML API.
nml = {}

---Repeats a string.
---
---With `separator` between the copies.
---@param text string
---@param count integer
---@param separator? string
---@return string
function nml.replicate(text, count, separator) end

---Calls `callback` with nothing.
---@param callback fun(): any
---@return any
function nml.call(callback) end

---Does nothing.
function nml.nothing() end
"
		);
	}

	#[test]
	fn writes_types() {
		let root = std::env::temp_dir().join(format!("nml-types-{}", std::process::id()));
		let _ = fs::remove_dir_all(&root);
		fs::create_dir_all(&root).unwrap();
		write_types(&root).unwrap();
		assert!(
			fs::read_to_string(root.join(".nml/types/nml.lua"))
				.unwrap()
				.starts_with("---@meta")
		);
		assert!(
			fs::read_to_string(root.join(".luarc.json"))
				.unwrap()
				.contains("Lua 5.4")
		);

		// An existing `.luarc.json` is the user's.
		fs::write(root.join(".luarc.json"), "{}").unwrap();
		write_types(&root).unwrap();
		assert_eq!(fs::read_to_string(root.join(".luarc.json")).unwrap(), "{}");
		fs::remove_dir_all(root).unwrap();
	}
}
